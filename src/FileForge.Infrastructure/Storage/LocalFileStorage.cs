using System.Security.Cryptography;
using FileForge.Application.Errors;
using FileForge.Application.Storage;
using Microsoft.Extensions.Options;

namespace FileForge.Infrastructure.Storage;

internal sealed class LocalFileStorage : IFileStorage
{
    private const int BufferSize = 81_920;
    private const int KeyLength = 32; // 16 random bytes written as hex

    private readonly string _root;

    public LocalFileStorage(IOptions<StorageOptions> options)
    {
        _root = Path.GetFullPath(options.Value.RootPath);
        Directory.CreateDirectory(_root);
    }

    public async Task<StoredFile> SaveAsync(Stream content, long maxBytes, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(content);

        var key = CreateKey();
        var path = GetPath(key);

        try
        {
            await using var output = new FileStream(
                path, FileMode.CreateNew, FileAccess.Write, FileShare.None, BufferSize, useAsync: true);

            var buffer = new byte[BufferSize];
            long total = 0;
            int read;

            // Copy chunk by chunk and count: the limit is enforced even if the declared size was a lie.
            while ((read = await content.ReadAsync(buffer, cancellationToken)) > 0)
            {
                total += read;
                if (total > maxBytes)
                {
                    throw new AppException(
                        ErrorCodes.FileTooLarge,
                        $"The file exceeds the maximum size of {maxBytes} bytes.");
                }

                await output.WriteAsync(buffer.AsMemory(0, read), cancellationToken);
            }

            return new StoredFile(key, total);
        }
        catch
        {
            // The output stream is already closed here (its scope ended), so the partial file can be removed.
            TryDelete(path);
            throw;
        }
    }

    public string CreateKey() => Convert.ToHexStringLower(RandomNumberGenerator.GetBytes(KeyLength / 2));

    public string GetLocalPath(string storageKey) => GetPath(storageKey);

    public long GetSize(string storageKey) => new FileInfo(GetPath(storageKey)).Length;

    public Stream OpenRead(string storageKey) =>
        new FileStream(GetPath(storageKey), FileMode.Open, FileAccess.Read, FileShare.Read, BufferSize, useAsync: true);

    public void Delete(string storageKey) => File.Delete(GetPath(storageKey));

    private string GetPath(string storageKey)
    {
        // Keys are generated by us, but a key like "..\..\secret" must never turn into a path, so check anyway.
        if (storageKey is not { Length: KeyLength } || !storageKey.All(char.IsAsciiHexDigitLower))
        {
            throw new ArgumentException("Invalid storage key.", nameof(storageKey));
        }

        return Path.Combine(_root, storageKey);
    }

    private static void TryDelete(string path)
    {
        try
        {
            File.Delete(path);
        }
        catch (IOException)
        {
            // Left for the orphan-file cleanup; the original exception matters more.
        }
    }
}
